 --Tabel drinks: tambah kolom user_id
alter table public.drinks
  add column if not exists user_id uuid references auth.users (id) on delete cascade;

create index if not exists drinks_user_id_idx on public.drinks (user_id);


--Tabel reminders 
create table if not exists public.reminders (
  id             bigint generated by default as identity primary key,
  user_id        uuid        not null references auth.users (id) on delete cascade,
  time           text        not null,              
  enabled        boolean     not null default true,
  type           text        not null default 'custom',
  last_fired_at  timestamptz,                   
  created_at     timestamptz not null default now()
);

create index if not exists reminders_user_id_idx on public.reminders (user_id);


--Tabel auto_reminders
create table if not exists public.auto_reminders (
  user_id           uuid primary key references auth.users (id) on delete cascade,
  enabled           boolean     not null default false,
  start_time        text        not null default '07:00',
  end_time          text        not null default '22:00',
  interval_minutes  integer     not null default 60,
  last_fired_at     timestamptz
);


--Tabel reminder_history (riwayat pengingat yang sudah bunyi)
create table if not exists public.reminder_history (
  id        bigint generated by default as identity primary key,
  user_id   uuid        not null references auth.users (id) on delete cascade,
  source    text        not null,                   
  time      text,
  title     text,
  message   text,
  fired_at  timestamptz not null default now()
);

create index if not exists reminder_history_user_id_idx on public.reminder_history (user_id);

 
-- Tabel push subscriptions untuk Web Push
create table if not exists public.push_subscriptions (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null references auth.users (id) on delete cascade,
  endpoint     text not null,
  p256dh       text not null,
  auth         text not null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique(user_id, endpoint)
);

create index if not exists push_subscriptions_user_id_idx on public.push_subscriptions (user_id);

alter table public.reminders        disable row level security;
alter table public.auto_reminders   disable row level security;
alter table public.reminder_history disable row level security;
alter table public.push_subscriptions disable row level security;
